def main() -> None:
    SOURCES_DIR.mkdir(parents=True, exist_ok=True)
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)

    # 1. Write source-registry.csv
    csv_path = SOURCES_DIR / "source-registry.csv"
    with csv_path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=FIELDNAMES)
        writer.writeheader()
        for row in SOURCES:
            writer.writerow(row)

    # 2. Write source-registry.json
    json_path = SOURCES_DIR / "source-registry.json"
    accessible_count = sum(1 for s in SOURCES if s["verification_status"] == "VERIFIED_ACCESSIBLE")
    inaccessible_count = sum(1 for s in SOURCES if s["verification_status"] == "SOURCE_INACCESSIBLE")
    payload = {
        "corpus_name": "Oxford Institute of Technology and Justice — AI Justice Atlas",
        "date_accessed": DATE_ACCESSED,
        "total_urls": len(SOURCES),
        "accessible_count": accessible_count,
        "inaccessible_count": inaccessible_count,
        "sources": SOURCES,
    }
    json_path.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")

    # 3. Write access-log.csv
    log_path = SOURCES_DIR / "access-log.csv"
    with log_path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=[
                "source_id",
                "jurisdiction",
                "url",
                "date_accessed",
                "access_method",
                "verification_status",
                "notes",
            ],
        )
        writer.writeheader()
        for s in SOURCES:
            note = (
                "Retrieved and audited from live page"
                if s["verification_status"] == "VERIFIED_ACCESSIBLE"
                else "Browse returned access failure; web search returned 0 indexed results; no content fabricated"
            )
            writer.writerow(
                {
                    "source_id": s["source_id"],
                    "jurisdiction": s["jurisdiction"],
                    "url": s["url"],
                    "date_accessed": s["date_accessed"],
                    "access_method": "google:browse",
                    "verification_status": s["verification_status"],
                    "notes": note,
                }
            )

    # 4. Write OXFORD_SOURCE_AUDIT.md
    audit_lines = [
        "# Oxford AI Justice Atlas — Source Audit Report",
        "",
        f"**Date Accessed:** {DATE_ACCESSED}  ",
        f"**Publisher:** {PUBLISHER}  ",
        f"**Total Supplied URLs:** {len(SOURCES)} (1 Hub + 46 Country Profiles)  ",
        f"**Verified Accessible:** {accessible_count}  ",
        f"**Inaccessible:** {inaccessible_count} (`OXF-AIATLAS-44` Zambia)",
        "",
        "## Audit Summary",
        "- All 47 supplied URLs were individually inspected using live web browsing.",
        "- The reconstructed Türkiye URL (`https://www.techandjustice.bsg.ox.ac.uk/research/t%C3%BCrkiye`) was verified accessible and indexed.",
        "- The Zambia URL (`https://www.techandjustice.bsg.ox.ac.uk/ai-use-in-zambias-criminal-justice-system-insights-and-regulation-ai-atlas`) returned an access failure and 0 search results; it is recorded as `SOURCE_INACCESSIBLE` with zero fabricated content.",
        "- All accessible records are strictly labeled `EXISTING_REAL_WORLD_RECORD` to preserve epistemic separation from proposed 12D research programs.",
        "",
        "## Cross-Jurisdictional Patterns Observed",
        "1. **Generative AI Hallucinations & Sanctions:** Documented judicial sanctions, nullifications, or formal admonitions appear across Australia (>30 cases), UK (*Ayinde*), US (*Mata v Avianca*), UAE (*Arabyads*), South Africa (*Parker*, *Mavundla*), Kenya (*Nayan Savla*), Zimbabwe (*Pulserate Investments v Zuze*), Italy (Florence/Latina), Argentina, and Singapore.",
        "2. **Judicial AI Governance & UNESCO Alignment:** Colombia (`Acuerdo PCSJA24-12243`) and the Philippines (`AM 25-11-28-SC`) explicitly operationalized UNESCO judicial AI guidelines; Brazil (`CNJ Res 615/2025`), EU Member States (EU AI Act), South Korea (`AI Framework Act`), Italy (`Law 132/2025`), and Uzbekistan (`Law ORK-1115`) enacted binding statutory or council rules.",
        "3. **Biometrics & Predictive Policing Pushback:** Courts or regulators halted, fined, or restricted FRT/predictive systems in Argentina (BA FRT), Canada (Clearview AI), Finland (Clearview AI), France (BriefCam, Art 33 predictive ban), Germany (*hessenDATA*), Italy (SARI Real-Time), the Netherlands (*SyRI*, Clearview EUR 30.5M, CAS, OxRec), Spain (Veripol discontinued, *1119/2025* source code access), UK (*Bridges*, HART ceased), and US (*Williams v Detroit*, Chicago ShotSpotter).",
        "4. **Multilingual Court Transcription & Access to Justice:** High-impact court ASR systems operate in India (SUVAS, Adalat AI), Estonia (Salme), Kenya, Tanzania (Kiswahili-English), the Philippines (Taglish Scriptix), Taiwan (Mandarin/Taiwanese/Hakka), and Egypt (>96% offline Arabic).",
        "",
        "## Source Registry Table",
        "| ID | Jurisdiction | Status | Title | URL |",
        "| :--- | :--- | :--- | :--- | :--- |",
    ]
    for s in SOURCES:
        title = s["source_title"] if s["source_title"] else "(Inaccessible)"
        audit_lines.append(
            f"| {s['source_id']} | {s['jurisdiction']} | {s['verification_status']} | {title} | {s['url']} |"
        )

    (REPORTS_DIR / "OXFORD_SOURCE_AUDIT.md").write_text("\n".join(audit_lines) + "\n", encoding="utf-8")
    print(f"Built registry: {len(SOURCES)} sources ({accessible_count} accessible, {inaccessible_count} inaccessible)")


if __name__ == "__main__":
    main()
